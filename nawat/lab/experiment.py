"""Experiments — one folder that holds everything about one training.

Planning an experiment freezes it::

    <workspace>/lab/experiments/<name>/
        experiment.json     what runs: backbone, blocks, every parameter, inputs, hashes
        plan.md             the same, as a table a person (or an agent) reads
        preset.toml         the effective preset, reusable as-is
        code/               byte-for-byte copies of the backbone and every block
        approval.json       written only by `nawat exp approve`, on the host, at a terminal
        run.py              the entry point the executor runs
        env.json            library versions, GPU and driver, written when it starts
        effective_config.json   every trainer field actually in force, defaults included
        traces/             every generation the model made while training
        eval/               measurements
        report.md           the summary written when it ends

The run imports blocks from ``code/``, not from the library, so editing or
deleting a library block later cannot change what an old experiment was — and
re-running it re-runs exactly that code.

**The approval gate.** An experiment does not start until a person has read its
parameter table and typed the short code printed under it. The code is the head
of a hash over the code snapshot, the parameters and the inputs, so changing any
of them after approval invalidates it. Approval needs an interactive terminal
and is refused inside the sandbox, so an agent can prepare an experiment but
cannot approve its own; and because the sandbox has no key to check a signature
with, a run there is started from the host, which checks it first.
"""

