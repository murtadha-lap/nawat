def param_rows(experiment: Experiment) -> list[tuple[str, str, str, str, str, str]]:
    """(slot, name, value, default, source, help) for every parameter, in plan order."""
    rows = []
    helps = experiment.data.get("param_help", {})
    sources = experiment.data.get("param_sources", {})
    for slot, values in experiment.data["params"].items():
        label = "train" if slot == "backbone" else slot
        for name, value in values.items():
            info = helps.get(slot, {}).get(name, {})
            source = sources.get(slot, {}).get(name, "")
            rows.append((label, name, format_value(value), format_value(info.get("default")), source, info.get("help", "")))
    return rows


def render_plan(experiment: Experiment, defaults: Mapping[str, Any] | None = None) -> str:
    d = experiment.data
    lines = [
        f"# Experiment plan: {d['name']}",
        "",
        f"- **Preset:** {d['preset']['name']} ({d['preset']['source']})" + (f" — {d['preset']['description']}" if d['preset'].get('description') else ""),
        f"- **Backbone:** {d['backbone']['name']} — {d['backbone'].get('summary', '')}",
        f"- **Model:** {d['inputs']['model'] or '—'}",
        f"- **Datasets:** {', '.join(d['inputs']['datasets']) or '—'}",
    ]
    if d.get("notes"):
        lines.append(f"- **Notes:** {d['notes']}")
    lines += ["", "## Blocks", "", "| slot | block | from | sha256 | what it does |", "| --- | --- | --- | --- | --- |"]
    lines.append(f"| backbone | {d['backbone']['name']} | {d['backbone']['source']} | {d['backbone']['sha256'][:12]} | {d['backbone'].get('summary', '')} |")
    for slot, entries in d["blocks"].items():
        for b in entries:
            lines.append(f"| {slot} | {b['name']} | {b['source']} | {b['sha256'][:12]} | {b.get('summary', '')} |")
    lines += ["", "## Every parameter", "", "| block | parameter | value | default | set by | meaning |", "| --- | --- | --- | --- | --- | --- |"]
    for slot, name, value, default, source, help_text in param_rows(experiment):
        mark = "" if source == "default" else " ◀"
        lines.append(f"| {slot} | `{name}` | `{value}`{mark} | `{default}` | {source} | {help_text.replace('|', '/')} |")
    if defaults:
        lines += ["", f"## Library defaults also in effect ({d['backbone'].get('config_class')})", "",
                  "Set by the trainer library, not by this experiment. Override any of them through `train.extra`.", "",
                  "| field | default |", "| --- | --- |"]
        lines += [f"| `{k}` | `{format_value(v) if not isinstance(v, (set, tuple)) else list(v)}` |" for k, v in sorted(defaults.items())]
    lines += [
        "",
        "## Approval",
        "",
        f"Approval code: **{experiment.code}** (plan hash `{d['plan_hash'][:16]}…`)",
        "",
        f"Approve at a terminal on the host: `nawat exp approve {d['name']}`",
        "",
    ]
    return "\n".join(lines)
