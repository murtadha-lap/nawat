class ApprovalRequired(NawatError):
    exit_code = 9


def experiments_root(config) -> Path:
    return lab_root(config) / "experiments"


def new_name(preset: str) -> str:
    return f"{preset}/{time.strftime('%Y%m%d')}-{uuid.uuid4().hex[:4]}"


def full_name(name: str | None, group: str) -> str:
    """Experiments are filed by group — the preset, unless chosen — so the bucket reads by line of research.

    ``my-run`` becomes ``<group>/my-run``; a name that already has a group keeps it.
    """
    if not name:
        return new_name(group)
    if "/" in name:
        return name
    return f"{group}/{name}"


@dataclass
class SlotPlan:
    slot: str
    block: Block
    params: Resolved

    @property
    def key(self) -> str:
        """Where its parameters live: ``model``, or ``rewards.exact-answer`` for list slots."""
        return f"{self.slot}.{self.block.name}" if self.slot in LIST_SLOTS else self.slot


@dataclass
class Experiment:
    dir: Path
    data: dict[str, Any] = field(default_factory=dict)

    @classmethod
    def load(cls, directory: Path) -> "Experiment":
        path = directory / FILE
        if not path.is_file():
            raise NotFound(f"{directory} is not an experiment folder.", "Plan one with: nawat exp plan <preset>")
        return cls(directory, json.loads(path.read_text()))

    @property
    def name(self) -> str:
        return self.data["name"]

    @property
    def plan_hash(self) -> str:
        return self.data["plan_hash"]

    @property
    def code(self) -> str:
        return self.plan_hash[:6].upper()

    @property
    def approval(self) -> dict[str, Any] | None:
        try:
            return json.loads((self.dir / APPROVAL).read_text())
        except (OSError, ValueError):
            return None

    @property
    def approved(self) -> bool:
        approval = self.approval
        return bool(approval and approval.get("plan_hash") == self.plan_hash)

    def path(self, *parts: str) -> Path:
        return self.dir.joinpath(*parts)

    def code_path(self, entry: Mapping[str, Any]) -> Path:
        return self.dir / entry["code"]

    def recompute_hash(self) -> str:
        """The plan hash from what is on disk now — the code files as well as the record."""
        entries = [self.data["backbone"], *[b for slot in self.data["blocks"].values() for b in slot]]
        if self.data.get("support"):
            entries.append(self.data["support"])
        for entry in entries:
            path = self.code_path(entry)
            if not path.is_file() or sha256_file(path) != entry["sha256"]:
                raise Protected(
                    f"{entry['code']} in experiment {self.name} differs from the plan.",
                    "The code an experiment runs is frozen when it is planned. Plan a new experiment instead.",
                )
        return plan_hash(self.data)

    def require_approved(self, config=None) -> None:
        """The gate. Raises unless a person approved exactly this plan (and, where the key is, signed it)."""
        current = self.recompute_hash()
        if current != self.plan_hash:
            raise Protected(f"Experiment {self.name} was changed after it was planned.", "Plan a new experiment instead.")
        approval = self.approval
        if not approval:
            raise ApprovalRequired(
                f"Experiment {self.name} has not been approved.",
                f"Read its parameters, then approve it at a terminal on the host: nawat exp approve {self.name}",
            )
        if approval.get("plan_hash") != current:
            raise ApprovalRequired(
                f"The approval of {self.name} was for a different plan.",
                f"Approve this plan again: nawat exp approve {self.name}",
            )
        state = approval_state(config, approval)
        if state == "forged":
            raise ApprovalRequired(
                f"The approval of {self.name} was not signed by `nawat exp approve` on this host.",
                f"Approve it yourself: nawat exp approve {self.name}",
            )
        if state == "unverified" and os.environ.get(SANDBOX_ENV) and os.environ.get(HOST_VERIFIED_ENV) != current:
            raise ApprovalRequired(
                f"The approval of {self.name} cannot be verified inside the sandbox, which has no key.",
                f"Start it from the host, which checks the signature and launches it here: nawat exp run {self.name}",
            )

    def attempts(self) -> list[str]:
        return list(self.data.get("attempts", []))

    def add_attempt(self, run_id: str) -> None:
        data = json.loads((self.dir / FILE).read_text())
        data.setdefault("attempts", []).append(run_id)
        _write_json(self.dir / FILE, data)
        self.data = data


def _key_path(config) -> Path:
    return Path(config.state_dir) / KEY_FILE


def approval_key(config, *, create: bool = False) -> bytes | None:
    path = _key_path(config)
    if path.is_file():
        return path.read_bytes()
    if not create:
        return None
    path.parent.mkdir(parents=True, exist_ok=True)
    key = secrets.token_bytes(32)
    fd = os.open(path, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
    with os.fdopen(fd, "wb") as handle:
        handle.write(key)
    return key


def sign(key: bytes, approval: Mapping[str, Any]) -> str:
    material = json.dumps({k: approval[k] for k in ("plan_hash", "approved_at", "approved_by", "host")}, sort_keys=True)
    return hmac.new(key, material.encode(), hashlib.sha256).hexdigest()


def approval_state(config, approval: Mapping[str, Any] | None) -> str:
    """verified | unverified (no key here: another machine or the sandbox) | forged | none."""
    if not approval:
        return "none"
    key = approval_key(config) if config is not None else None
    if key is None:
        return "unverified"
    signature = approval.get("signature")
    return "verified" if signature and hmac.compare_digest(signature, sign(key, approval)) else "forged"


def plan_hash(data: Mapping[str, Any]) -> str:
    """Everything that decides what an experiment does, and nothing else."""
    material = {
        "backbone": [data["backbone"]["name"], data["backbone"]["sha256"]],
        "support": (data.get("support") or {}).get("sha256"),
        "blocks": {slot: [[b["name"], b["sha256"]] for b in entries] for slot, entries in sorted(data["blocks"].items())},
        "params": data["params"],
        "inputs": data["inputs"],
    }
    return hashlib.sha256(json.dumps(material, sort_keys=True, default=str).encode()).hexdigest()


def _write_json(path: Path, data: Any) -> None:
    tmp = path.with_suffix(path.suffix + ".tmp")
    tmp.write_text(json.dumps(data, indent=2, default=str) + "\n")
    os.replace(tmp, path)


