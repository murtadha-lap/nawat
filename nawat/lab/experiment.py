def resolve_plan(
    library: Library,
    preset: Preset,
    sets: Mapping[str, Any] = {},
) -> tuple[Block, Resolved, list[SlotPlan]]:
    """Choose every block and value for a preset, or say exactly what is wrong."""
    backbone = library.get(preset.backbone, "backbone")
    library.check_unchanged(backbone)
    slots_wanted: Mapping[str, str] = backbone.meta.get("slots", {})
    model_types = tuple(backbone.meta.get("models", ()))

    set_layers: dict[str, dict[str, Any]] = {}
    for dotted, value in sets.items():
        from .presets import split_param

        slot_key, name = split_param(dotted)
        set_layers.setdefault(slot_key, {})[name] = value

    plans: list[SlotPlan] = []
    for slot in SLOTS:
        names = preset.slot_blocks(slot)
        need = slots_wanted.get(slot)
        if need is None:
            if names and slot != "runtime":
                raise BlockError(f"Backbone {backbone.name} has no {slot} slot, but the preset fills it.",
                                 f"Remove it with --use {slot}=none, or pick a backbone that takes one.")
        if need == "required" and not names:
            raise BlockError(f"Backbone {backbone.name} needs a {slot} block and the preset has none.",
                             f"Choose one with --use {slot}=<name>. List them with: nawat block ls {slot}")
        if slot == "runtime" and not names:
            names = ["host"]
        if slot not in LIST_SLOTS and len(names) > 1:
            raise BlockError(f"The {slot} slot takes one block, not {len(names)}.")
        for name in names:
            block = library.get(name, slot)
            library.check_unchanged(block)
            if not block.fits(backbone):
                raise BlockError(
                    f"{block.ref} is written for {', '.join(block.meta.get('backbones', ()))}, not {backbone.name}.",
                    f"Pick a {slot} block made for {backbone.name}: nawat block ls {slot}",
                )
            if slot == "model" and model_types and block.meta.get("model_type") not in model_types:
                raise BlockError(
                    f"{block.ref} loads a {block.meta.get('model_type')} model; backbone {backbone.name} trains {', '.join(model_types)}.",
                )
            key = f"{slot}.{name}" if slot in LIST_SLOTS else slot
            layers = [("preset", preset.params.get(key, {})), ("--set", set_layers.pop(key, {}))]
            plans.append(SlotPlan(slot, block, resolve(key, block.params, layers)))

    backbone_params = resolve(
        "train", backbone.params,
        [("preset", preset.params.get("backbone", {})), ("--set", set_layers.pop("backbone", {}))],
    )
    used = {"backbone", *(p.key for p in plans)}
    stray = (set(preset.params) - used) | set(set_layers)
    if stray:
        raise BlockError(f"Parameters are set for blocks this experiment does not use: {', '.join(sorted(stray))}.",
                         "Remove them, or add the block they belong to.")
    model_block = next((p.block for p in plans if p.slot == "model"), None)
    if model_block is not None:
        model_type = model_block.meta.get("model_type")
        for plan in plans:
            fit = plan.block.meta.get("models")
            if fit and model_type not in fit:
                raise BlockError(f"{plan.block.ref} works with {', '.join(fit)} models, but {model_block.ref} loads a {model_type} model.")
    return backbone, backbone_params, plans


def plan_experiment(
    config,
    preset_name: str,
    *,
    name: str | None = None,
    sets: Mapping[str, Any] = {},
    uses: Mapping[str, str] = {},
    model: str | None = None,
    datasets: list[str] | None = None,
    notes: str = "",
    group: str | None = None,
    store=None,
    sweep: str | None = None,
) -> Experiment:
    presets = Presets(config)
    library = Library(config)
    preset = presets.get(preset_name)
    if uses:
        apply_uses(preset, uses)
    if model:
        preset.model = model
    if datasets:
        preset.datasets = list(datasets)
    backbone, backbone_params, plans = resolve_plan(library, preset, sets)

    inputs = {
        "model": str(Key.parse(preset.model)) if preset.model else None,
        "datasets": [str(Key.parse(d)) for d in preset.datasets],
        "inputs": [str(Key.parse(i)) for i in preset.inputs],
    }
    modules = {plan.key: load_module(plan.block.path, plan.block.ref) for plan in plans}
    for plan in plans:
        declare = getattr(modules[plan.key], "inputs", None)
        if callable(declare):
            for key in declare(Params(plan.block.ref, plan.params.values)) or ():
                key = str(Key.parse(key))
                if key not in inputs["inputs"] and key != inputs["model"] and key not in inputs["datasets"]:
                    inputs["inputs"].append(key)
    if backbone.meta.get("slots", {}).get("model") == "required" and not inputs["model"]:
        raise BlockError("This experiment has no model.", "Give one with --model models/<repo>, or set model = ... in the preset.")
    if backbone.meta.get("slots", {}).get("dataset") == "required" and not inputs["datasets"]:
        raise BlockError("This experiment has no dataset.", "Give one with --dataset datasets/<name>, or set dataset = ... in the preset.")

    name = validate_run_name(full_name(name, group or preset.name))
    if name.count("/") != 1:
        raise BlockError(f"{name!r}: an experiment is named <group>/<name>, with exactly one '/'.",
                         "Leave the group out to file it under its preset, or pass --group.")
    directory = experiments_root(config) / name
    if directory.exists():
        raise Protected(f"Experiment {name!r} already exists.", "Experiment names are permanent; choose another.")
    if store is not None:
        try:
            if store.list_prefix(Key.parse(f"runs/{name}")):
                raise Protected(f"Object storage already holds runs/{name}.", "Choose another name, or remove it with: nawat store rm runs/" + name)
        except StoreUnavailable:
            pass

    directory.mkdir(parents=True)
    try:
        def snapshot(block: Block, where: str) -> dict[str, Any]:
            target = directory / "code" / where / f"{block.name}.py"
            target.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(block.path, target)
            target.chmod(0o444)
            return {**block.to_json(), "code": str(target.relative_to(directory)), "summary": block.summary}

        blocks: dict[str, list[dict[str, Any]]] = {}
        params: dict[str, dict[str, Any]] = {"backbone": backbone_params.values}
        sources: dict[str, dict[str, str]] = {"backbone": backbone_params.sources}
        for plan in plans:
            blocks.setdefault(plan.slot, []).append(snapshot(plan.block, plan.slot))
            params[plan.key] = plan.params.values
            sources[plan.key] = plan.params.sources

        effective = Preset(
            name=name, backbone=backbone.name, description=preset.description, model=inputs["model"],
            datasets=inputs["datasets"], inputs=inputs["inputs"],
            blocks={slot: ([b["name"] for b in entries] if slot in LIST_SLOTS else entries[0]["name"]) for slot, entries in blocks.items()},
            params={k: v for k, v in params.items()}, parent=preset.name,
        )
        support_src = Path(__file__).resolve().parent / "support.py"
        support_dst = directory / "code" / "support.py"
        support_dst.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(support_src, support_dst)
        support_dst.chmod(0o444)
        data: dict[str, Any] = {
            "name": name,
            "group": name.split("/", 1)[0],
            "sweep": sweep,
            "created_at": time.time(),
            "created_by": getpass.getuser(),
            "host": socket.gethostname(),
            "notes": notes,
            "preset": {"name": preset.name, "source": preset.source, "sha256": preset.sha256, "parent": preset.parent,
                       "description": preset.description},
            "backbone": {**snapshot(backbone, "backbone"), "config_class": backbone.meta.get("config_class")},
            "blocks": blocks,
            "params": params,
            "param_sources": sources,
            "param_help": _help(backbone, plans),
            "inputs": inputs,
            "support": {"name": "support", "kind": "support", "source": "builtin", "code": "code/support.py",
                        "sha256": sha256_file(support_dst)},
            "attempts": [],
        }
        data["plan_hash"] = plan_hash(data)
        data["eval_fingerprints"] = eval_fingerprints(data, plans)
        _write_json(directory / FILE, data)
        (directory / "preset.toml").write_text(effective.to_toml())
        (directory / "run.py").write_text(RUN_PY.format(name=name))
        experiment = Experiment(directory, data)
        (directory / "plan.md").write_text(render_plan(experiment, library_defaults(data)))
    except BaseException:
        shutil.rmtree(directory, ignore_errors=True)
        raise

    library.lock(backbone, name)
    for plan in plans:
        library.lock(plan.block, name)
    return experiment


def eval_fingerprints(data: Mapping[str, Any], plans: list[SlotPlan]) -> dict[str, str]:
    """What each measurement depends on, hashed: two experiments compare on an eval only if these match.

    The eval block's code and parameters (test set, metric, generation settings)
    and the inputs it declares always count. An eval that scores a held-out part
    of the training data (``BLOCK["uses_training_data"]``) also depends on the
    dataset and on the dataset block that split it, so it only compares across
    experiments trained on the same data split the same way.
    """
    dataset = next((p for p in plans if p.slot == "dataset"), None)
    out = {}
    for plan in plans:
        if plan.slot != "eval":
            continue
        material: dict[str, Any] = {"block": [plan.block.name, plan.block.sha256], "params": plan.params.values,
                                    "support": (data.get("support") or {}).get("sha256")}
        module = load_module(plan.block.path, plan.block.ref)
        declare = getattr(module, "inputs", None)
        if callable(declare):
            material["inputs"] = sorted(str(k) for k in (declare(Params(plan.block.ref, plan.params.values)) or ()))
        if plan.block.meta.get("uses_training_data") and dataset is not None:
            material["data"] = {"datasets": data["inputs"]["datasets"], "block": [dataset.block.name, dataset.block.sha256],
                                "params": dataset.params.values}
        out[plan.block.name] = hashlib.sha256(json.dumps(material, sort_keys=True, default=str).encode()).hexdigest()
    return out


def _help(backbone: Block, plans: list[SlotPlan]) -> dict[str, dict[str, Any]]:
    def describe(spec: P) -> dict[str, Any]:
        return {"default": spec.default, "help": spec.help, "choices": list(spec.choices) if spec.choices else None}

    out = {"backbone": {n: describe(s) for n, s in backbone.params.items()}}
    for plan in plans:
        out[plan.key] = {n: describe(s) for n, s in plan.block.params.items()}
    return out


def library_defaults(data: Mapping[str, Any]) -> dict[str, Any] | None:
    """Trainer fields this experiment does not set, with the library's default for each.

    Nothing about a run should be invisible, including what the trainer library
    decides on its own. Needs the trainer library importable; returns None when
    it is not (a storage-only machine), and the run records the full effective
    config when it starts either way.
    """
    target = (data.get("backbone") or {}).get("config_class")
    if not target:
        return None
    try:
        import dataclasses
        import importlib

        module_name, _, cls_name = target.rpartition(".")
        cls = getattr(importlib.import_module(module_name), cls_name)
    except Exception:  # noqa: BLE001 - optional: torch may be absent or broken here
        return None
    ours = set(data["params"].get("backbone", {}))
    out: dict[str, Any] = {}
    for f in dataclasses.fields(cls):
        if f.name in ours or f.name.startswith("_"):
            continue
        if f.default is not dataclasses.MISSING:
            value = f.default
        elif f.default_factory is not dataclasses.MISSING:  # type: ignore[misc]
            try:
                value = f.default_factory()  # type: ignore[misc]
            except Exception:  # noqa: BLE001
                value = "<factory>"
        else:
            continue
        out[f.name] = value
    return out


# -- approval -----------------------------------------------------------------


def approve(experiment: Experiment, typed: str, config=None) -> dict[str, Any]:
    if os.environ.get(SANDBOX_ENV):
        raise Protected("Experiments cannot be approved from inside the sandbox.",
                        f"Approve it on the host: nawat exp approve {experiment.name}")
    current = experiment.recompute_hash()
    if typed.strip().upper() != current[:6].upper():
        raise ApprovalRequired("That is not the approval code for this plan.", "Nothing was approved. Read the table and type the code shown under it.")
    approval = {
        "plan_hash": current,
        "approved_at": time.time(),
        "approved_by": getpass.getuser(),
        "host": socket.gethostname(),
    }
    if config is not None:
        approval["signature"] = sign(approval_key(config, create=True), approval)
    _write_json(experiment.dir / APPROVAL, approval)
    return approval


def find(config, name: str) -> Experiment:
    directory = experiments_root(config) / name
    if "/" not in name and not (directory / FILE).is_file():
        matches = [e for e in list_experiments(config) if e.name.split("/", 1)[-1] == name]
        if len(matches) == 1:
            return matches[0]
        if len(matches) > 1:
            raise NotFound(f"{name!r} matches several experiments: {', '.join(e.name for e in matches)}.", "Give the full <group>/<name>.")
    if not (directory / FILE).is_file():
        path = Path(name).expanduser()
        if (path / FILE).is_file():
            return Experiment.load(path)
        listed = [e.name for e in list_experiments(config)]
        import difflib

        close = difflib.get_close_matches(name, listed, n=3)
        raise NotFound(f"No experiment named {name!r} in {experiments_root(config)}.",
                       (f"Did you mean: {', '.join(close)}? " if close else "") + "List them with: nawat exp ls")
    return Experiment.load(directory)


def list_experiments(config) -> list[Experiment]:
    root = experiments_root(config)
    if not root.is_dir():
        return []
    out = []
    for path in root.glob(f"*/*/{FILE}"):
        try:
            out.append(Experiment.load(path.parent))
        except (OSError, ValueError):
            continue
    return sorted(out, key=lambda e: e.data.get("created_at", 0))


