"""The OpenCode sandbox — an isolated machine-inside-the-machine for an agent that trains models.

A Docker container with:

- **full control inside**: root, a terminal, ``apt``/``uv pip install`` of anything;
- **the GPU** (``--gpus all``) and **the network**;
- **the workspace** mounted read-write at ``/workspace`` — the lab, its blocks,
  presets and experiments — and nothing else of the host's file system;
- **its own cache** (a Docker volume), so it never touches the host's cache
  database, and the **object-store credentials**, so what it trains is published
  to the same bucket;
- **OpenCode** (opencode.ai) installed, with ``AGENTS.md`` telling it the rules.

What it cannot do: approve an experiment (approval needs the host), or delete
from object storage. It prepares plans; a person approves them.

Optional, like every block: an experiment runs in it only when its preset sets
``runtime = "sandbox"``.
"""

from __future__ import annotations

import os
import shutil
import subprocess
import tempfile
from pathlib import Path
from urllib.parse import urlparse

from ..errors import NawatError

IMAGE = "nawat-sandbox:latest"
CONTAINER = "nawat-sandbox"
CACHE_VOLUME = "nawat-sandbox-cache"
HOME_VOLUME = "nawat-sandbox-home"

#: The training stack, as the README installs it — kept in one place so the
#: sandbox and the host agree.
TRAINING_STACK = r"""
uv pip install "torch==2.8.0" "triton>=3.3.0" numpy pillow torchvision bitsandbytes xformers==0.0.32.post2 \
  "unsloth_zoo[base] @ git+https://github.com/unslothai/unsloth-zoo" \
  "unsloth[base] @ git+https://github.com/unslothai/unsloth"
uv pip install --no-deps "torchcodec==0.7.0"
uv pip install --upgrade --no-deps "tokenizers>=0.22.0,<=0.23.0" trl==0.22.2 unsloth unsloth_zoo
uv pip install transformers==5.2.0 sentence-transformers snac torchaudio
uv pip install --no-build-isolation flash-linear-attention "causal_conv1d==1.6.0"
uv pip install --no-deps --upgrade "torchao>=0.16.0"
uv pip install "vllm==0.11.0"
"""

DOCKERFILE = """\
# Nawāt OpenCode sandbox. Generated by `nawat sandbox dockerfile`.
FROM nvidia/cuda:12.8.1-cudnn-devel-ubuntu24.04
ENV DEBIAN_FRONTEND=noninteractive PYTHONUNBUFFERED=1 UV_LINK_MODE=copy
RUN apt-get update && apt-get install -y --no-install-recommends \\
      curl ca-certificates git build-essential ffmpeg libsndfile1 tini sudo less nano jq unzip \\
    && rm -rf /var/lib/apt/lists/*
COPY --from=ghcr.io/astral-sh/uv:latest /uv /uvx /usr/local/bin/
RUN uv venv /opt/venv --python 3.12
ENV VIRTUAL_ENV=/opt/venv PATH=/opt/venv/bin:/root/.opencode/bin:$PATH
COPY training-stack.sh /opt/training-stack.sh
RUN bash -euxo pipefail /opt/training-stack.sh
COPY nawat-src /opt/nawat-src
RUN uv pip install -e "/opt/nawat-src[notebook]"
RUN curl -fsSL https://opencode.ai/install | bash
ENV NAWAT_SANDBOX=1 NAWAT_WORKSPACE=/workspace NAWAT_CACHE_ROOT=/cache
WORKDIR /workspace
ENTRYPOINT ["/usr/bin/tini", "--"]
CMD ["sleep", "infinity"]
"""

AGENTS_MD = """\
# Rules for agents in this workspace (Nawāt lab)

You are training models inside an isolated sandbox. You have root, the GPU and
the network here; install what you need. The host is protected — work only
under /workspace.

## How training works here

There is exactly one way to train: an approved experiment. Nawāt refuses
anything else — there is no command that runs an arbitrary script, the
executor runs only approved experiments, `nawat.begin_run()` refuses, and
`runs/` in object storage only accepts what experiments produce.

1. Never write training code from scratch. Training runs through a **fixed
   backbone** per method (sft, cpt, dpo, grpo — DAPO/GSPO are grpo presets —
   tts, stt, embedding, decision), copied from the official Unsloth notebooks.
   List them: `nawat block ls backbone`.
2. Everything that changes is a **block**: model, dataset, template, rewards,
   eval, export. `nawat block ls`, `nawat block show <kind>/<name>`.
3. **Never edit a block or preset in place.** Copy it first:
   `nawat block fork dataset/chat-messages --as my-data`, then edit
   `lab/blocks/dataset/my-data.py`. Save a new preset that uses it:
   `nawat preset fork llm-sft --as my-sft --use dataset=my-data`.
4. **Every number is a parameter.** Do not hard-code values in block code; add
   them to the block's PARAMS. Change values with `--set`, never by editing code:
   `nawat preset fork llm-grpo --as grpo-lr --set train.learning_rate=1e-5`.
5. **Ask the user about parameters before planning.** Show them the preset's
   parameters (`nawat preset show <name>`) and ask which to change, especially
   learning rate, steps, batch size, LoRA rank, max lengths and the dataset's
   columns and processing.
6. Plan: `nawat exp plan <preset> [--set ...]`. This prints every parameter and
   an approval code. **You cannot approve.** Tell the user to run
   `nawat exp approve <experiment>` on the host, and wait.
7. Run after approval: `nawat exp run <experiment>`.
8. Read results: `nawat exp report <experiment>`, `nawat exp compare A B`,
   `nawat exp traces <experiment>`. Reports are plain text written for you.

## Not allowed

- approving experiments, deleting from object storage (`nawat store rm`),
  editing files under `lab/experiments/*/code/`, or editing locked blocks;
- training outside an experiment (a script of your own, a notebook, a direct
  Unsloth/TRL call) — its results are not recorded, and do not count.
"""


def docker() -> str:
    path = shutil.which("docker")
    if not path:
        raise NawatError(
            "Docker is not installed, so the sandbox cannot run.",
            "Install Docker Engine and the NVIDIA Container Toolkit "
            "(https://docs.docker.com/engine/install/ and "
            "https://docs.nvidia.com/datacenter/cloud-native/container-toolkit/latest/install-guide.html), "
            "then: nawat sandbox build",
        )
    return path


def repo_root() -> Path:
    return Path(__file__).resolve().parents[2]


def build_context(target: Path) -> Path:
    """A build context with the Dockerfile, the training stack and Nawāt's source."""
    target.mkdir(parents=True, exist_ok=True)
    (target / "Dockerfile").write_text(DOCKERFILE)
    (target / "training-stack.sh").write_text(TRAINING_STACK.strip() + "\n")
    source = target / "nawat-src"
    root = repo_root()
    source.mkdir(exist_ok=True)
    for name in ("pyproject.toml", "README.md", "LICENSE"):
        if (root / name).is_file():
            shutil.copy2(root / name, source / name)
    shutil.copytree(root / "nawat", source / "nawat", dirs_exist_ok=True,
                    ignore=shutil.ignore_patterns("__pycache__", "*.pyc"))
    return target


def sandbox_env(config, network: str) -> dict[str, str]:
    """Credentials and endpoints the container gets. Loopback endpoints need the host's network."""
    env = {
        "NAWAT_S3_BUCKET": config.bucket,
        "NAWAT_S3_PREFIX": config.store_prefix,
        "NAWAT_S3_REGION": config.region,
        "NAWAT_STORE_BACKEND": config.store_backend,
        "NAWAT_CACHE_CEILING": str(config.cache_ceiling),
        "NAWAT_MIN_FREE": str(config.min_free),
    }
    if config.endpoint:
        env["NAWAT_S3_ENDPOINT"] = config.endpoint
    if config.access_key:
        env["NAWAT_S3_ACCESS_KEY"] = config.access_key
    if config.secret_key:
        env["NAWAT_S3_SECRET_KEY"] = config.secret_key
    if config.hub_token:
        env["HF_TOKEN"] = config.hub_token
    return env


def choose_network(config, requested: str) -> str:
    if requested != "auto":
        return requested
    host = urlparse(config.endpoint or "").hostname or ""
    # A store listening on the host's loopback is unreachable from a bridged container.
    return "host" if host in ("127.0.0.1", "localhost", "::1") else "bridge"


def run_args(config, *, image: str, name: str, network: str, gpus: str) -> tuple[list[str], dict[str, str]]:
    network = choose_network(config, network)
    env = sandbox_env(config, network)
    args = [docker(), "run", "-d", "--name", name, "--hostname", name, "--restart", "unless-stopped",
            "--network", network, "-v", f"{config.workspace_root}:/workspace", "-v", f"{CACHE_VOLUME}:/cache",
            "-v", f"{HOME_VOLUME}:/root", "--shm-size", "8g"]
    if gpus:
        args += ["--gpus", gpus]
    for key in env:
        args += ["-e", key]  # values come from the environment of the docker process, not the command line
    args += [image, "sleep", "infinity"]
    return args, env


def write_agents_md(config) -> Path | None:
    path = Path(config.workspace_root) / "AGENTS.md"
    if path.exists():
        return None
    path.write_text(AGENTS_MD)
    return path


def running(name: str = CONTAINER) -> bool:
    try:
        out = subprocess.run([docker(), "inspect", "-f", "{{.State.Running}}", name], capture_output=True, text=True)
    except NawatError:
        return False
    return out.returncode == 0 and out.stdout.strip() == "true"


def exec_args(name: str, command: list[str], *, interactive: bool, workdir: str = "/workspace") -> list[str]:
    flags = ["-it"] if interactive else ["-i"]
    return [docker(), "exec", *flags, "-w", workdir, name, *command]


def call(args: list[str], env: dict[str, str] | None = None) -> int:
    merged = {**os.environ, **(env or {})}
    return subprocess.call(args, env=merged)


def build(tag: str = IMAGE) -> int:
    with tempfile.TemporaryDirectory() as scratch:
        context = build_context(Path(scratch) / "context")
        return call([docker(), "build", "-t", tag, str(context)])
